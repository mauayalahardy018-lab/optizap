export function formatPriceMXN(price: number): string {
  return new Intl.NumberFormat("es-MX", {
    style: "currency",
    currency: "MXN",
    minimumFractionDigits: 2,
  }).format(price);
}

export function formatFrameMeasurements(
  frame: Pick<Frame, "lens_width_mm" | "bridge_width_mm" | "temple_length_mm">
): string {
  return `${frame.lens_width_mm}-${frame.bridge_width_mm}-${frame.temple_length_mm}`;
}
